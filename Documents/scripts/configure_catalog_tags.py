def run():
    print(f"Connecting to Postgres at {PG_HOST}:{PG_PORT}/{PG_DB}...")
    conn = psycopg.connect(
        f"postgresql://{PG_USER}:{PG_PASS}@{PG_HOST}:{PG_PORT}/{PG_DB}",
        row_factory=dict_row
    )
    with conn.cursor() as cur:
        # Ensure schema column exists
        cur.execute("ALTER TABLE documents ADD COLUMN IF NOT EXISTS catalog_metadata jsonb NOT NULL DEFAULT '{}'::jsonb")
        cur.execute("GRANT SELECT, UPDATE ON documents TO viio_documents")
        conn.commit()

    print(f"Sending metadata updates via API: {DOCUMENTS_URL}...")
    client = httpx.Client(timeout=30.0)
    success = 0
    for doc_id, meta in METADATA_MAP.items():
        resp = client.post(
            f"{DOCUMENTS_URL}/api/v1/documents/catalog/{doc_id}/metadata",
            headers={"X-Internal-Token": ADMIN_KEY},
            json=meta
        )
        if resp.status_code == 200:
            success += 1
        else:
            print(f"Error updating {doc_id}: {resp.status_code} {resp.text}")
    print(f"Updated {success}/{len(METADATA_MAP)} documents successfully.")

    # Verification
    rag_resp = client.post(
        f"{DOCUMENTS_URL}/api/v1/knowledge/documents",
        headers={"X-Internal-Token": READ_KEY},
        json={"limit": 5, "offset": 0, "user_context": {"role": "admin"}}
    )
    if rag_resp.status_code == 200:
        data = rag_resp.json()
        print(f"Verification: total={data.get('total')}, untagged_count={data.get('untagged_count')}")


if __name__ == "__main__":
    run()
